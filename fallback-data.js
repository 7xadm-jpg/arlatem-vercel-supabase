  function merge(remote) {
    const current = remote && typeof remote === 'object' ? remote : {};
    const merged = { ...DEFAULT_DATA, ...current };
    arrayKeys.forEach((key) => {
      merged[key] = Array.isArray(current[key]) && current[key].length
        ? current[key]
        : (DEFAULT_DATA[key] || []);
    });
    merged.settings = { ...(DEFAULT_DATA.settings || {}), ...(current.settings || {}) };
    merged.hero = { ...(DEFAULT_DATA.hero || {}), ...(current.hero || {}) };
    merged.banner = { ...(DEFAULT_DATA.banner || {}), ...(current.banner || {}) };
    merged.about = {
      ...(DEFAULT_DATA.about || {}),
      ...(current.about || {}),
      points: Array.isArray(current.about?.points) && current.about.points.length
        ? current.about.points
        : (DEFAULT_DATA.about?.points || []),
      specs: Array.isArray(current.about?.specs) && current.about.specs.length
        ? current.about.specs
        : (DEFAULT_DATA.about?.specs || [])
    };
    return merged;
  }

  async function load() {
    try {
      const response = await fetch('/api/content', { cache: 'no-store' });
      if (!response.ok) throw new Error('API indisponivel');
      const payload = await response.json();
      if (!payload?.ok || !payload.data) throw new Error('Resposta invalida');
      return { ok: true, data: merge(payload.data) };
    } catch (error) {
      console.warn('Conteudo local de seguranca ativado.');
      return { ok: true, data: merge({}) };
    }
  }

